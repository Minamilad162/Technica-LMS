import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const root = new URL('../',import.meta.url);
const file = p=>readFileSync(new URL(p,root),'utf8');
const catalog = JSON.parse(file('src/data/aspDomains.json'));
assert.equal(catalog.length,5,'ASP retains five imported workbook domains');
const source=file('src/lib/adminCourses.js');
const moduleSource=source.replace("import {courses as importedCourses} from '../data/courseCatalog.js';", `const importedCourses = [{id:'asp',name:'ASP Course',domainIds:${JSON.stringify(catalog.map(x=>x.id))}},{id:'psee',name:'PSEE',domainIds:[]}];`);
const {allAdminCourses,courseStatus,validateCourse,createCourseId,courseMediaFor}=await import('data:text/javascript;base64,'+Buffer.from(moduleSource).toString('base64'));
const state={createdCourses:[],courseEdits:{},courseMedia:[]};
assert.equal(allAdminCourses(state).length,2);
assert.equal(courseStatus(allAdminCourses(state)[0]),'published');
assert.equal(courseStatus(allAdminCourses(state)[1]),'draft');
const now=Date.now();
const scheduled={id:'new',name:'New Course',status:'scheduled',publishAt:new Date(now+3600000).toISOString()};
assert.equal(courseStatus(scheduled,now),'scheduled');
assert.equal(courseStatus(scheduled,now+3600001),'published');
assert.match(validateCourse({name:'a',status:'draft'},allAdminCourses(state)),/at least 3/);
assert.match(validateCourse({name:'PSEE',status:'draft'},allAdminCourses(state)),/already exists/);
assert.match(validateCourse({...scheduled,publishAt:new Date(now-3600).toISOString()},allAdminCourses(state)),/future/);
assert.equal(validateCourse(scheduled,allAdminCourses(state)),'');
assert.equal(createCourseId('Safety Leadership',allAdminCourses(state)),'safety-leadership');
assert.equal(createCourseId('ASP Course',allAdminCourses(state)),'asp-course');
const stage={...state,createdCourses:[scheduled],courseEdits:{psee:{description:'Edited course shell',status:'published'}},courseMedia:[{id:'media-1',courseId:'new',kind:'pdf'}]};
assert.equal(allAdminCourses(stage).length,3);
assert.equal(allAdminCourses(stage).find(c=>c.id==='psee').description,'Edited course shell');
assert.equal(courseMediaFor(stage,'new').length,1);
assert.equal(courseMediaFor(stage,'asp').some(m=>m.sample),true);
assert.match(file('src/App.jsx'),/path="\/courses"/);
assert.ok(file('src/App.jsx').includes('function AdminOnly'));
assert.match(file('src/components/Layout.jsx'),/\['\/courses','Courses'/);
assert.ok(!file('src/components/Layout.jsx').includes("['/builder','Media library'"));
assert.ok(!file('src/pages/AnalyticsPage.jsx').includes('ASP question bank coverage'));
assert.ok(file('src/pages/AnalyticsPage.jsx').includes('setSelectedLearner(l)'));
assert.ok(file('src/pages/BuilderPage.jsx').includes('CourseMaterialsPanel courseId={activeCourse.id}'));
assert.ok(file('src/components/CourseMaterialsPanel.jsx').includes('await saveMedia(id,file)'));
assert.ok(file('src/lib/store.jsx').includes('createAdminCourse,editAdminCourse,addCourseMedia,deleteCourseMedia'));
console.log('PASS: Course CRUD helpers, status/scheduling, sample media isolation, nav/overview/profile, and upload integration.');
