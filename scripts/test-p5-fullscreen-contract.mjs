import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {
 isNativeFullscreenAvailable,isFullscreenActive,requestQuestionFullscreen,
 leaveQuestionFullscreen,fullscreenStartError
} from '../src/lib/questionFullscreen.js';
const doc={fullscreenEnabled:true,fullscreenElement:null};
const element={ownerDocument:doc,requestFullscreen:async()=>{doc.fullscreenElement=element;}};
doc.documentElement=element;
doc.exitFullscreen=async()=>{doc.fullscreenElement=null;};
assert.equal(isNativeFullscreenAvailable(doc,element),true);
assert.equal(isFullscreenActive(doc,element),false);
assert.deepEqual(await requestQuestionFullscreen(element),{ok:true,reason:'entered'});
assert.equal(isFullscreenActive(doc,element),true);
await leaveQuestionFullscreen(doc);
assert.equal(isFullscreenActive(doc,element),false);
assert.equal(isNativeFullscreenAvailable({...doc,fullscreenEnabled:false},element),false);
assert.deepEqual(await requestQuestionFullscreen({ownerDocument:{fullscreenEnabled:false}}),{ok:false,reason:'unsupported'});
const rejectedDoc={fullscreenEnabled:true,fullscreenElement:null};
const rejected={ownerDocument:rejectedDoc,requestFullscreen:async()=>{throw Error('Denied')}};
assert.deepEqual(await requestQuestionFullscreen(rejected),{ok:false,reason:'denied'});
assert.match(fullscreenStartError({reason:'unsupported'}),/iPhone/);
assert.match(fullscreenStartError({reason:'denied'}),/Fullscreen permission/);
const code=path=>readFileSync(path,'utf8');
const practice=code('src/pages/PracticePage.jsx');
const assessment=code('src/pages/AssessmentOverview.jsx');
const quiz=code('src/pages/QuizPage.jsx');
const store=code('src/lib/store.jsx');
const hook=code('src/lib/useQuestionFullscreenGuard.js');
const live=code('src/production/LivePractice.jsx');
const watermark=code('src/production/LiveProtectedContent.jsx');
const api=code('src/production/practiceApi.js');
const sql=code('supabase/migrations/202611030001_p5_fullscreen_attempt_exit.sql');
assert(practice.includes('requestQuestionFullscreen(document.documentElement)'));
assert(assessment.includes('requestQuestionFullscreen(document.documentElement)'));
assert(quiz.includes('useQuestionFullscreenGuard')&&quiz.includes('abortSession(kind)'));
assert(quiz.includes('isFullscreenActive(document)'));
assert(store.includes('function abortSession(kind)'));
assert(hook.includes("'fullscreenchange'")&&hook.includes("'visibilitychange'"));
assert(hook.includes('leaveIntentionally'));
assert(live.includes('requestQuestionFullscreen(containerRef.current)'));
assert(live.includes('useQuestionFullscreenGuard'));
assert(live.includes('LiveProtectedContent'));
assert(live.includes('abandonSecurePractice'));
assert(live.includes("storageKey+':closing'"));
assert(!live.includes("getSecurePractice(db,saved.attemptId)"),'Reload must not automatically reveal old questions');
assert(!watermark.includes("getAuthSession"),'Live watermark must not include demo login code');
assert(watermark.includes('watermarkIdentity(identitySource)'));
assert(api.includes("'lms_p5_abandon_practice'"));
assert(sql.includes("state IN ('in_progress','submitted','expired','abandoned')"));
assert(sql.includes("IF a.state='abandoned' THEN"));
assert(sql.includes("'questions','[]'::jsonb"));
assert(sql.includes("CREATE FUNCTION public.lms_p5_abandon_practice"));
assert(sql.includes("WHERE id=p_attempt_id AND user_id=(SELECT auth.uid()) FOR UPDATE"));
assert(sql.includes("GRANT EXECUTE ON FUNCTION public.lms_p5_abandon_practice(uuid) TO authenticated,service_role"));
console.log('PASS P5: native fullscreen activation, demo exit to setup, live watermark and server-abandoned privacy contract');
