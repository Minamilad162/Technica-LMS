import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {formatWatermarkLabel,mediaWatermarkTiles,watermarkIdentity} from '../src/lib/contentProtection.js';
const at=new Date('2026-11-11T14:00:00.000Z'),session='A1B2C3D4E5F6';
const now=mediaWatermarkTiles({sessionId:session,time:at});
const next=mediaWatermarkTiles({sessionId:session,time:new Date(at.getTime()+45000)});
assert.equal(now.length,3);
assert.notDeepEqual(now,next,'session marks move every 45s');
for(const tile of [...now,...next]){
 assert.ok(tile.top>=10&&tile.top<=80,'safe vertical position');
 assert.ok(tile.left>=10&&tile.left<=65,'safe horizontal position');
}
assert.deepEqual(now,mediaWatermarkTiles({sessionId:session,time:at}));
const id=watermarkIdentity('abc123-USER_9876543210');
assert.match(formatWatermarkLabel({identity:id,sessionId:session,time:at}),/TECHNICA.*A1B2C3D4E5F6.*UTC/);
const read=p=>readFileSync(p,'utf8');
const viewer=read('src/production/ProtectedLessonViewer.jsx'),lesson=read('src/production/CourseLessonExplorer.jsx');
const legacy=read('src/production/LiveLearning.jsx'),surface=read('src/production/LiveProtectedContent.jsx');
const api=read('src/production/lessonMediaApi.js'),edge=read('supabase/functions/technica-lesson-media/index.ts');
assert.match(surface,/useLayoutEffect\(\(\)=>\{\s*activeProtectedContainers\+\+/);
assert.match(surface,/kind==='lesson-surface'/);
assert.match(viewer,/getContentProtectionSession/);
assert.match(viewer,/mediaWatermarkTiles\(\{sessionId,time\}\)/);
assert.match(viewer,/positions\.map\(\(\{top,left\},i\)/);
assert.match(viewer,/authorizeLessonMedia\(db,lessonId,block\)/);
assert.match(viewer,/src=\{url\}/);
assert.match(viewer,/disablePictureInPicture/);
assert.match(viewer,/referrerPolicy="no-referrer"/);
assert.match(lesson,/identity=\{adminPreview\?'ADMIN PREVIEW':userId\}/);
assert.match(lesson,/viewerId=\{adminPreview\?'ADMIN PREVIEW':userId\}/);
assert.match(legacy,/viewerId=\{data\?\.user\?\.id\|\|'LEARNER'\}/);
assert.match(api,/action:'view'/);
assert.doesNotMatch(api,/\.getPublicUrl\(/);
assert.match(edge,/auth\.getUser\(token\)/);
assert.match(edge,/createSignedUrl\(asset\.private_object_path,READ_SECONDS\)/);
assert.match(edge,/READ_SECONDS=120/);
assert.doesNotMatch(viewer,/widevine|playready|paidDrm|externalDrm/i);
console.log('PASS P69 zero-install automatic Lesson protection and session watermark');
console.log('LIMIT: OS screenshots, recording, PDF saves and signed URL extraction remain possible.');
