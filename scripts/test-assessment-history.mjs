import assert from 'node:assert/strict';
import {archiveAssessment,hydrateAssessment,assessmentHistoryForUser,groupAssessmentHistory} from '../src/lib/assessmentHistory.js';
import bank from '../src/data/aspQuestionBank.json' with {type:'json'};

const first=bank[0],other=bank[1];
const make=(courseId,attempt,when,kind='assessment')=>({kind,courseId,courseName:courseId==='asp'?'ASP Course':'Other Course',attempt,submittedAt:when,passMark:70,timeTaken:'12:03',answers:{1:first.correct,2:undefined},flags:[2],questions:[{...first,id:1},{...other,id:2}]});
const r1=make('asp',1,'2026-10-25T10:00:00.000Z');
const r2=make('asp',2,'2026-10-26T10:00:00.000Z');
const p1=make('asp',1,'2026-10-26T09:00:00.000Z','practice');
const r3=make('psee',1,'2026-10-27T10:00:00.000Z');
assert.equal(archiveAssessment(p1,'learner-a'),null,'Practice must never be archived as an assessment');
const a1=archiveAssessment(r1,'learner-a'),a2=archiveAssessment(r2,'learner-a'),a3=archiveAssessment(r3,'learner-a');
assert.equal(a1.questions,undefined,'History should store lightweight ASP references rather than duplicate full bank content');
assert.equal(a1.questionRefs[0].bankId,first.bankId);
const hydrated=hydrateAssessment(a1,bank);
assert.equal(hydrated.questions[0].prompt,first.prompt);
assert.equal(hydrated.questions[0].correct,first.correct);
assert.equal(hydrated.questions[1].id,2);
assert.equal(hydrated.answers[1],first.correct);
assert.equal(hydrated.answers[2],undefined);
const state={assessmentHistory:[a1,a2,a3,archiveAssessment(make('asp',1,'2026-10-27T11:00:00.000Z'),'learner-b')],lastResult:p1};
const records=assessmentHistoryForUser(state,'learner-a',bank);
assert.equal(records.length,3,'Only this learner’s assessment attempts should appear');
const groups=groupAssessmentHistory(records);
assert.deepEqual(groups.map(g=>g.courseId),['psee','asp']);
assert.deepEqual(groups.find(g=>g.courseId==='asp').attempts.map(r=>r.attempt),[2,1]);
assert.equal(assessmentHistoryForUser(state,'learner-b',bank).length,1);
assert.equal(assessmentHistoryForUser(state,'learner-c',bank).length,0);
const withLegacy=assessmentHistoryForUser({assessmentHistory:[a1],lastResult:r2},'demo-learner',bank);
assert.equal(withLegacy.length,1,'Legacy lastResult should not leak to other learner accounts');
const demoLegacy=assessmentHistoryForUser({assessmentHistory:[],lastResult:r1},'demo-learner',bank);
assert.equal(demoLegacy.length,1,'Old assessment lastResult must be available to the original sample user');
const noDuplicate=assessmentHistoryForUser({assessmentHistory:[archiveAssessment(r1,'demo-learner')],lastResult:r1},'demo-learner',bank);
assert.equal(noDuplicate.length,1,'Latest assessment should not duplicate a history record');
const laterPractice=assessmentHistoryForUser({assessmentHistory:[archiveAssessment(r1,'demo-learner')],lastResult:p1},'demo-learner',bank);
assert.equal(laterPractice.length,1,'Practice after assessment should never erase course history');
const custom={...make('asp',3,'2026-10-27T11:00:00.000Z'),questions:[{id:1,bankId:'custom-123',correct:1,prompt:'Custom question',options:['One','Two'],explanation:'Custom explanation',topic:'Domain 1',reference:'Author'}]};
const customResult=hydrateAssessment(archiveAssessment(custom,'learner-a'),bank);
assert.equal(customResult.questions[0].prompt,'Custom question','Custom questions need a snapshot for future review');
assert.equal(groupAssessmentHistory([]).length,0,'Empty history must render an empty state');
console.log('PASS: 13 course review history checks — course scoping, chronology, practice exclusion, account isolation, legacy migration, snapshots, retakes');
