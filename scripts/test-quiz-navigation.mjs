import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {getUnansweredQuestionIds,getSkippedQuestionIds,markQuestionLeft} from '../src/lib/quizNavigation.js';
const bank=JSON.parse(readFileSync(new URL('../src/data/aspQuestionBank.json',import.meta.url)));
assert.equal(bank.length,1625);
// Option A is index 0 and MUST count as an answer; visited unanswered are emphasized.
assert.deepEqual(getUnansweredQuestionIds(5,{1:0,2:2,4:3}),[3,5]);
assert.deepEqual(getUnansweredQuestionIds(5,{1:0,2:2,3:1,4:3,5:0}),[]);
assert.deepEqual(getUnansweredQuestionIds(3,{}),[1,2,3]);
assert.deepEqual(getSkippedQuestionIds(5,{1:0,2:2,4:3},[2,3,3,4]),[3]);
assert.deepEqual(getSkippedQuestionIds(4,{},[1,3]),[1,3]);
assert.deepEqual(markQuestionLeft([],1,5),[1]);
assert.deepEqual(markQuestionLeft([1],1,5),[1]);
assert.deepEqual(markQuestionLeft([1],4,5),[1,4]);
assert.deepEqual(markQuestionLeft([1],6,5),[1]);
assert.deepEqual(getUnansweredQuestionIds(50,Object.fromEntries(Array.from({length:49},(_,i)=>[i+1,i%4]))),[50]);
const quiz=readFileSync(new URL('../src/pages/QuizPage.jsx',import.meta.url),'utf8');
const store=readFileSync(new URL('../src/lib/store.jsx',import.meta.url),'utf8');
const assessment=readFileSync(new URL('../src/pages/AssessmentOverview.jsx',import.meta.url),'utf8');
const css=readFileSync(new URL('../src/courseModel.css',import.meta.url),'utf8');
assert(quiz.includes('getSkippedQuestionIds')&&quiz.includes('showAllUnanswered'));
assert(quiz.includes('Submit with unanswered')&&quiz.includes('Review unanswered'));
assert(quiz.includes('Question navigator')&&quiz.includes('unanswered-mark'));
assert(quiz.includes('role="alert"')&&quiz.includes('aria-label={`Question ${id}'));
assert(store.includes('visitedQuestions:[]')&&store.includes('markQuestionLeft'));
assert(!assessment.includes('assessment-locked-setup')&&!css.includes('locked-assessment-grid'));
console.log('PASS: 1,625 source questions intact; both quiz modes share skipped/unanswered detection; navigator warnings; last-question review; intentional incomplete submission; assessment summary simplified.');
