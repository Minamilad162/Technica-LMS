import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {getUnansweredQuestionIds,markQuestionLeft} from '../src/lib/quizNavigation.js';
const bank=JSON.parse(readFileSync(new URL('../src/data/aspQuestionBank.json',import.meta.url)));
assert.equal(bank.length,1625);
assert.deepEqual(getUnansweredQuestionIds(5,{1:0,2:2,4:3}),[3,5]);
assert.deepEqual(getUnansweredQuestionIds(5,{1:0,2:2,3:1,4:3,5:0}),[]);
assert.deepEqual(getUnansweredQuestionIds(3,{}),[1,2,3]);
assert.deepEqual(markQuestionLeft([],1,5),[1]);
assert.deepEqual(markQuestionLeft([1],6,5),[1]);
assert.deepEqual(getUnansweredQuestionIds(50,Object.fromEntries(Array.from({length:49},(_,i)=>[i+1,i%4]))),[50]);
const quiz=readFileSync(new URL('../src/pages/QuizPage.jsx',import.meta.url),'utf8');
const assessment=readFileSync(new URL('../src/pages/AssessmentOverview.jsx',import.meta.url),'utf8');
const store=readFileSync(new URL('../src/lib/store.jsx',import.meta.url),'utf8');
// Markers must be gated behind the learner's FINAL review action, never Next.
assert.ok(quiz.includes('showAllUnanswered?unansweredIds:[]'));
assert.ok(!quiz.includes('getSkippedQuestionIds'));
assert.ok(quiz.includes('function openReview()')&&quiz.includes('setShowAllUnanswered(true)'));
assert.ok(quiz.includes("function next(){if(current===count)openReview();else jump(kind,current+1)}"));
assert.ok(quiz.includes('Submit with unanswered')&&quiz.includes('Review unanswered'));
assert.ok(quiz.includes('Question navigator')&&quiz.includes('unanswered-mark'));
assert.ok(quiz.includes('role="alert"')&&quiz.includes('aria-label={`Question ${id}'));
assert.ok(store.includes('visitedQuestions:[]')&&store.includes('markQuestionLeft'));
assert.ok(assessment.includes('Review and submit'));
console.log('PASS: unanswered navigator warnings appear ONLY on final Review and submit; incomplete submissions remain explicit for Practice and Assessment.');
