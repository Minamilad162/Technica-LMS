import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {getCourseHierarchy,hierarchySummary,moveItem,validateCourseHierarchy,newHierarchyId} from '../src/lib/courseHierarchy.js';
const legacy=[{id:'old-1',title:'PSM Foundations',lessons:[{id:'existing-lesson',title:'Intro',type:'Video',mediaId:'asset-1'}]}];
const state={courseHierarchies:{}};
const initial=getCourseHierarchy(state,'asp',legacy);
assert.equal(initial.length,1);
assert.equal(initial[0].title,'Unmapped legacy content');
assert.equal(initial[0].legacyUnmapped,true);
assert.equal(initial[0].topics[0].lessons[0].mediaId,'asset-1');
assert.equal(initial[0].topics[0].lessons[0].id,'existing-lesson');
assert.deepEqual(hierarchySummary(initial),{domains:1,topics:1,lessons:1});
assert.equal(validateCourseHierarchy(initial),null);
const other={id:'d-new',title:'Domain A',topics:[{id:'t-new',title:'Topic A',lessons:[{id:'l-new',title:'Lesson A',type:'Text',description:'Test'}]}]};
const changed=[...initial,other];
assert.equal(validateCourseHierarchy(changed),null);
assert.equal(moveItem(changed,other.id,-1)[0].id,other.id);
assert.equal(moveItem(changed,other.id,+1)[1].id,other.id);
assert.equal(validateCourseHierarchy([...changed,{...other}]).includes('Duplicate'),true);
assert.equal(validateCourseHierarchy([{id:'bad',title:'',topics:[]}]),'Domain title is required');
assert.equal(validateCourseHierarchy([{id:'d',title:'D',topics:[{id:'t',title:'T',lessons:[{id:'l',title:'L',type:'Unknown'}]}]}]),'Unknown lesson type');
assert.equal(getCourseHierarchy({...state,courseHierarchies:{asp:changed}},'asp',legacy).length,2);
assert.equal(getCourseHierarchy({...state,courseHierarchies:{asp:changed}},'other',[]).length,0);
assert.equal(legacy[0].lessons[0].id,'existing-lesson');
assert(newHierarchyId('topic').startsWith('topic-'));
const builder=readFileSync('src/pages/BuilderPage.jsx','utf8');
const store=readFileSync('src/lib/store.jsx','utf8');
assert(builder.includes('<CourseHierarchyEditor'));
assert(builder.includes('Legacy modules (compatibility'));
assert(store.includes('saveCourseHierarchy'));
assert(builder.includes('addModule(activeCourse.id)')); // preserve existing legacy authoring test
console.log('PASS course hierarchy: nested roles, legacy safety, per-course storage, order, IDs, authoring UI.');
