import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const f = name=>readFileSync(new URL('../'+name,import.meta.url),'utf8');
const page=f('src/pages/CoursesPage.jsx');
const css=f('src/courseDialog.css');
const main=f('src/main.jsx');
assert.match(page,/createPortal\(/,'dialog must render through a portal outside transformed page');
assert.match(page,/document\.body/,'portal destination must be document body');
assert.match(page,/onKeyDown=\{trapTab\}/,'keyboard must remain in dialog');
assert.match(page,/e\.key==='Escape'/,'Escape must dismiss');
assert.match(page,/previousOverflow/,'restore body overflow on close');
assert.match(page,/role="dialog" aria-modal="true" aria-labelledby=\{titleId\}/,'accessible dialog');
assert.match(page,/className="course-dialog-scroll"/);
assert.match(page,/className="course-dialog-header"/);
assert.match(page,/className="course-dialog-footer"/);
assert.match(page,/type="submit" form="admin-course-form"/,'sticky footer should submit actual form');
assert.match(page,/id="admin-course-form" className="simple-fields course-dialog-form" onSubmit=\{submit\}/);
assert.match(page,/editing==='new'\?'Create course':'Save changes'/,'edit mode retained');
assert.match(page,/Schedule publication/,'scheduling retained');
assert.match(css,/\.course-dialog-scroll\s*\{[^}]*overflow-y:auto/s,'only form content scrolls');
assert.match(css,/\.course-dialog\s*\{[^}]*display:flex;flex-direction:column/s,'bounded flex modal');
assert.match(css,/max-height:calc\(100dvh/,'uses dynamic viewport height');
assert.match(css,/\.course-dialog-footer\s*\{[^}]*flex:0 0 auto/s,'footer must never scroll out');
assert.ok(main.includes("import './courseDialog.css';"));
console.log('PASS: Course dialog portal, accessible keyboard behavior, bounded scrolling, fixed header/footer and form submit linkage.');
