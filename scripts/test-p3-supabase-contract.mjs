import assert from 'node:assert/strict';
import {readFileSync,readdirSync,statSync} from 'node:fs';
import {join} from 'node:path';
import {courseSlug,unusedSlug,nestStructure,updateTitle,updatePublish} from '../src/production/lmsApi.js';

assert.equal(courseSlug('ASP Safety & Health'),'asp-safety-health');
assert.equal(courseSlug('    '),'course');
assert.equal(unusedSlug('ASP',[{slug:'asp'},{slug:'asp-2'}]),'asp-3');
const domains=[{id:'d1',title:'D'},{id:'d2',title:'Other'}], topics=[{id:'t1',domain_id:'d1',title:'Topic'}],lessons=[{id:'l1',topic_id:'t1',title:'L'}];
const tree=nestStructure(domains,topics,lessons);
assert.equal(tree.length,2);
assert.equal(tree[0].topics[0].lessons[0].id,'l1');
assert.equal(tree[1].topics.length,0);
assert.equal(domains[0].topics,undefined,'do not mutate existing records');
let calls=[];
const mock={from:table=>({update:row=>({eq:async(column,id)=>{calls.push({table,row,column,id});return {error:null};}})})};
await updateTitle(mock,'lms_domains','id-1','New title');
await updatePublish(mock,'lms_lessons','id-2','published');
assert.equal(calls.length,2);
assert.deepEqual(calls[0],{table:'lms_domains',row:{title:'New title'},column:'id',id:'id-1'});
assert.deepEqual(calls[1].row,{publication_state:'published'});
await assert.rejects(()=>updateTitle(mock,'lms_role_assignments','id','admin'),/Invalid table/);
await assert.rejects(()=>updatePublish(mock,'lms_courses','id','invalid'),/Invalid publication state/);
