import assert from 'node:assert/strict';
import fs from 'node:fs';
import {courses,aspCourse,courseQuestionCount} from '../src/data/courseCatalog.js';
import {assessmentSettings,prepareAssessment,canPracticeCourse} from '../src/lib/courseAssessment.js';
import {createQuestionSet} from '../src/lib/questionSelection.js';
const bank=JSON.parse(fs.readFileSync(new URL('../src/data/aspQuestionBank.json',import.meta.url)));
assert.deepEqual(courses.map(c=>c.id),['asp','psee']);
assert.equal(aspCourse.name,'ASP Course');
assert.deepEqual(aspCourse.domainIds,['domain1','domain2','domain3','domain4','domain5']);
assert.equal(courseQuestionCount(aspCourse,bank),1625);
assert.equal(courseQuestionCount(courses[1],bank),0);
assert.equal(canPracticeCourse('asp',bank),true);
assert.equal(canPracticeCourse('psee',bank),false);
assert.equal(assessmentSettings('psee').enabled,false);
const set=assessmentSettings('asp');
assert.equal(set.questionCount,50);assert.equal(set.durationMinutes,60);assert.equal(set.passMark,70);
const result=prepareAssessment({courseId:'asp',settings:{},bank,attempts:0,random:()=>.5});
assert.ok(!result.error);assert.equal(result.questions.length,50);
assert.equal(new Set(result.questions.map(q=>q.bankId)).size,50);
assert.deepEqual(Object.values(Object.groupBy(result.questions,q=>q.domainId)).map(q=>q.length).sort(),[10,10,10,10,10]);
for(const q of result.questions) assert.ok(aspCourse.domainIds.includes(q.domainId));
assert.match(prepareAssessment({courseId:'psee',settings:{},bank}).error,/coming soon/i);
const overridden={asp:{questionCount:25,durationMinutes:42,passMark:82,maxAttempts:2,domainIds:['domain4'],enabled:true}};
const configured=prepareAssessment({courseId:'asp',settings:overridden,bank,attempts:1});
assert.ok(!configured.error);assert.equal(configured.questions.length,25);
assert.ok(configured.questions.every(q=>q.domainId==='domain4'));
assert.equal(configured.config.durationMinutes,42);assert.equal(configured.config.passMark,82);
assert.match(prepareAssessment({courseId:'asp',settings:overridden,bank,attempts:2}).error,/no assessment attempts/i);
const disabled={asp:{enabled:false}};
assert.match(prepareAssessment({courseId:'asp',settings:disabled,bank}).error,/coming soon/i);
assert.equal(assessmentSettings('asp',{asp:{questionCount:800}}).questionCount,50);
const practice=createQuestionSet({bank,domainIds:['domain2'],count:12});
assert.equal(practice.questions.length,12);assert.ok(practice.questions.every(q=>q.domainId==='domain2'));
const ui=fs.readFileSync(new URL('../src/pages/AssessmentOverview.jsx',import.meta.url),'utf8');
assert.ok(!ui.includes('SelectButtons'));
assert.ok(!ui.includes('assessmentQuestionCount'));
assert.ok(ui.includes('read only'));
const admin=fs.readFileSync(new URL('../src/pages/BuilderPage.jsx',import.meta.url),'utf8');
assert.ok(admin.includes('updateAssessmentSettings'));
assert.ok(admin.includes('Assessment'));
console.log('PASS: ASP parent course / 5 imported domains / 1,625 questions / PSEE empty / admin locked assessment / learner practice customization / pass mark and attempts.');
