import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {COURSE_CATEGORIES,getCourse,getCourseBank,getCourseModules,learnerCourses,courseDomainId} from '../src/lib/courseWorkspace.js';
import {normalizeQuestionRows,parseCSV} from '../src/lib/questionImport.js';
import {assessmentSettings,prepareAssessment,canPracticeCourse} from '../src/lib/courseAssessment.js';
const questionPool=JSON.parse(readFileSync(resolve('src/data/aspQuestionBank.json'),'utf8'));
const created={id:'process-engineering',name:'Process Engineering',category:'Process Safety',description:'Custom course',status:'draft',domainIds:[courseDomainId('process-engineering')]};
const state={modules:[{id:'asp-m1',title:'ASP',lessons:[{id:'l1'}]}],createdCourses:[created],courseModules:{'process-engineering':[{id:'new-m1',title:'Module 1',lessons:[{title:'Intro',type:'PDF',mediaId:'resource1'}]}]},addedQuestions:[]};
assert(COURSE_CATEGORIES.includes('Process Safety'));
assert.deepEqual(getCourseModules(state,'asp').map(x=>x.id),['asp-m1']);
assert.deepEqual(getCourseModules(state,created.id).map(x=>x.id),['new-m1']);
assert.equal(getCourseModules(state,'psee').length,0);
assert.deepEqual(getCourse(state,created.id).domainIds,[courseDomainId(created.id)]);
assert(!learnerCourses(state).some(c=>c.id===created.id));
created.status='published';assert(learnerCourses(state).some(c=>c.id===created.id));
const csv='Question,Option 1,Option 2,Option 3,Option 4,Correct Answer,Explanation,Domain\n"When is it safe, according to the plan?","Before briefing","After clearance","Without permission",,B,"After clearance",General\n';
const parsed=parseCSV(csv);assert.equal(parsed.length,2);
const ans=normalizeQuestionRows(parsed,{courseId:created.id,domainId:courseDomainId(created.id),sheetName:'General'});
assert.equal(ans.problems.length,0);assert.equal(ans.questions.length,1);assert.equal(ans.questions[0].correct,1);
assert.equal(ans.questions[0].options.length,3);
assert.equal(ans.questions[0].courseId,created.id);
const malformed=normalizeQuestionRows([parsed[0],['Bad','One','Two','','','E']],{courseId:created.id,domainId:courseDomainId(created.id)});
assert.equal(malformed.questions.length,0);assert.equal(malformed.problems.length,1);
const twoSheets=normalizeQuestionRows([['Question','Choice A','Choice B','Choice C','Correct Answer'],['Inspection?','Yes','No','Sometimes','A']],{courseId:'asp',domainId:'domain1',sheetName:'Domain 3'});
assert.equal(twoSheets.questions[0].domainId,'domain3');
const bank=[...questionPool,...ans.questions];const stateWith={...state,addedQuestions:ans.questions};
assert.equal(getCourseBank(stateWith,created.id,questionPool).length,1);
assert.equal(getCourseBank(stateWith,'asp',questionPool).length,1625);
assert.equal(getCourseBank(stateWith,'psee',questionPool).length,12);
assert(getCourseBank(stateWith,'psee',questionPool).every(q=>q.sample&&q.courseId==='psee'));
assert.equal(getCourseBank(stateWith,'asp',questionPool).length,1625);
assert(canPracticeCourse(created.id,ans.questions,getCourse(stateWith,created.id)));
const config=assessmentSettings(created.id,{},getCourse(stateWith,created.id));
assert.equal(config.enabled,false);
const settings={[created.id]:{enabled:true,questionCount:1,durationMinutes:15,passMark:80,domainIds:[courseDomainId(created.id)]}};
const prepared=prepareAssessment({courseId:created.id,course:getCourse(stateWith,created.id),settings,bank:ans.questions});
assert.equal(prepared.questions.length,1);assert.equal(prepared.config.passMark,80);
assert.equal(prepareAssessment({courseId:created.id,course:getCourse(stateWith,created.id),settings:{},bank:ans.questions}).error.includes('coming soon'),true);
assert.equal(getCourseBank(stateWith,'asp',questionPool)[0].bankId,questionPool[0].bankId);
const source=readFileSync(resolve('src/pages/BuilderPage.jsx'),'utf8');
assert(!source.includes("activeCourse.id==='asp'&&state.modules"));
assert(!source.includes('lesson editor below is available for the ASP sample course'));
assert(source.includes('importQuestionFile('));
assert(source.includes('addModule(activeCourse.id)'));
assert(source.includes('attachLessonFile'));
assert(source.includes('Preview attached file'));
const coursePage=readFileSync(resolve('src/pages/CoursesPage.jsx'),'utf8');
assert(coursePage.includes('COURSE_CATEGORIES'));
assert(coursePage.includes('<label>Course category<select'));
console.log('PASS: course-specific modules and content, learner visibility on publish, per-course banks, 3-choice Excel normalization, validation, admin-locked assessments, category dropdown and old ASP bank regression.');
