import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {getCourseBank} from '../src/lib/courseWorkspace.js';
import {pseeDemoQuestions} from '../src/data/pseeDemoQuestions.js';
import {allAdminCourses} from '../src/lib/adminCourses.js';
const root = new URL('../',import.meta.url);
const read = path=>readFileSync(new URL(path,root),'utf8');
const asp=JSON.parse(read('src/data/aspQuestionBank.json'));
const state={createdCourses:[{id:'new-course',name:'New course',status:'draft',domainIds:['course-new-course']}],courseEdits:{},addedQuestions:[{id:'custom-1',bankId:'custom-1',courseId:'new-course',domainId:'course-new-course',prompt:'New item',options:['Yes','No','Unknown'],correct:0,topic:'Demo'}]};
assert.equal(asp.length,1625,'Original ASP bank must remain unchanged');
assert.equal(getCourseBank(state,'asp',asp).length,1625);
assert.equal(pseeDemoQuestions.length,12);
assert.equal(getCourseBank(state,'psee',asp).length,12);
assert(getCourseBank(state,'psee',asp).every(q=>q.sample===true&&q.courseId==='psee'&&q.bankId.startsWith('PSEE-DEMO-')));
assert.equal(getCourseBank(state,'new-course',asp).length,1);
assert.equal(allAdminCourses(state).length,3);
const ids=[...getCourseBank(state,'asp',asp),...getCourseBank(state,'psee',asp)].map(q=>q.bankId);
assert.equal(ids.length,new Set(ids).size,'Banks must not share IDs');
const app=read('src/App.jsx');
assert.match(app,/path="\/question-bank" element=\{<AdminOnly>/,'Direct URL must be admin protected');
assert.match(app,/getAuthSession\(\)\?\.role==='admin'/,'Guard must use authenticated session role');
const nav=read('src/components/Layout.jsx');
const learner=nav.match(/const learnerItems=\[(.*?)\];/s)?.[1]||'';
assert(!learner.includes('/question-bank'),'Question bank must not appear in learner menu');
assert(nav.includes("['/question-bank','Question Bank',FileQuestion]"),'Question bank must remain in admin menu');
assert(nav.includes('adminSession&&<button'),'Learners cannot promote themselves to admin from account menu');
const saved=read('src/pages/SavedPage.jsx');
assert(saved.includes('bank-course-selector')&&saved.includes('All courses'));
assert(saved.includes('getCourseBank(state,c.id,questionPool)'),'Course-filtered data must use each course bank');
assert(saved.includes('Demo sample')&&saved.includes('PSEE questions are fictional'));
const auth=read('src/lib/demoAuth.js');
assert(auth.includes('DEMO_ADMIN_LOGIN')&&auth.includes("role:'admin'"));
const builder=read('src/pages/BuilderPage.jsx');
assert(builder.includes('`/question-bank?course=${activeCourse.id}`'));
console.log('PASS: 1,625 ASP questions preserved; 12 PSEE dummy questions; custom-course isolation; course-first selector; admin-only menu, route and session role; saved questions retained.');
